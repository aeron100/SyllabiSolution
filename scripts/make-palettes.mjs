import path from 'node:path';

const T = (token) => {
  if (token === 'white') return '#ffffff';
  if (token.startsWith('#')) return token.toLowerCase(); // literal brand-guide value
  const [hue, step] = token.split('-');
  const v = colors[hue]?.[step];
  if (!v) throw new Error(`unknown tailwind token ${token}`);
  return v.toLowerCase();
};

